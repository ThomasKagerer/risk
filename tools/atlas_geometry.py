def rounded_path(points):
    """Tiny rounded corners retain the coastline character without pixel staircases."""
    result = []
    for i, (x, y) in enumerate(points):
        before, after = points[i - 1], points[(i + 1) % len(points)]
        def approach(p):
            dx, dy = p[0] - x, p[1] - y
            ratio = min(.16, 1.2 / (dx * dx + dy * dy) ** .5)
            return x + dx * ratio, y + dy * ratio
        a, b = approach(before), approach(after)
        result.append(f'{"M" if i == 0 else "L"}{a[0]:.1f},{a[1]:.1f}Q{x},{y} {b[0]:.1f},{b[1]:.1f}')
    return ''.join(result) + 'Z'


def apply_atlas(data):
    from terrain_rules import classic_terrain
    classic_terrain(data)
    for c in data['countries']:
        (c['x'], c['y']), polygon = LANDS[c['id']]
        points = [tuple(map(int, p.split(','))) for p in polygon.split()]
        c['path'] = rounded_path(points)
        # Card silhouettes can use these bounds without forcing SVG layout.
        xs, ys = zip(*points)
        c['bounds'] = [min(xs), min(ys), max(xs) - min(xs), max(ys) - min(ys)]
    # House map: Ontario has no direct sea route to Greenland. Apply after import too.
    for a, b in ((7, 6), (6, 7)):
        data['countries'][a - 1]['neighbors'] = [n for n in data['countries'][a - 1]['neighbors'] if n != b]
    # Every non-touching playable pair has an explicit sea route.
    data['routes'] = [[1,38],[2,6],[8,6],[6,14],[14,15],[14,17],
                      [15,17],[17,18],[17,19],[19,21],[20,21],[20,22],
                      [12,21],[24,26],[25,26],[33,39],[39,40],[39,41],
                      [40,41],[40,42],[36,37],[37,38],[20,31],[22,31]]
    data['artwork'] = 'atlas-02'
    from build_continents import add_continents
    add_continents(data)
    return data


